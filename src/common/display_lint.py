"""
Validator for display declaration blocks (docs/conventions/display_conventions_v1.md).

Scans every *.display.txt under runs/ and reports DC1-DC8 compliance.
Report only: a violation makes a FRAME non-citable, not a run invalid.
Exit code is always 0, consistent with symbol_lint / provenance_lint.
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
RUNS = os.path.join(ROOT, 'runs')

REQUIRED = ('FRAME', 'PROVENANCE', 'STAGE', 'FIDELITY', 'BAND', 'COLOUR',
            'COLOUR-BASIS', 'SCALAR', 'TIME', 'GEOMETRY', 'ENHANCEMENT', 'ME5-COROLLARY')

ENUM = {
    'PROVENANCE':     {'CHAIN-EVIDENCE', 'BOUNDARY-INPUT', 'NEITHER'},
    'STAGE':          {'S0', 'S1', 'S2', 'S3', 'S4'},
    'FIDELITY':       {'FL1', 'FL2', 'FL3'},
    'COLOUR':         {'DECLARED-CONVENTION', 'PHYSICAL', 'NONE'},
    'GEOMETRY':       {'PRESCRIBED (D2)', 'SOLVED'},
    'ME5-COROLLARY':  {'PRESENT', 'NOT-APPLICABLE'},
}

ENHANCEMENTS = {'EN1', 'EN2', 'EN3', 'EN4', 'EN5', 'none'}


def parse(path):
    out = {}
    with open(path, 'r', encoding='utf-8', errors='replace') as f:
        for line in f:
            if ':' in line:
                k, _, v = line.partition(':')
                k = k.strip()
                if k and not k.startswith('#'):
                    out[k] = v.strip()
    return out


def check(path):
    """Return list of (rule, message)."""
    bad = []
    d = parse(path)
    for f in REQUIRED:
        if f not in d:
            bad.append(('DC1', 'missing field %s' % f))
    if bad:
        return bad

    for f, allowed in ENUM.items():
        if d[f] not in allowed:
            bad.append(('DC1', '%s = %r not in %s' % (f, d[f], sorted(allowed))))

    if d['COLOUR'] == 'DECLARED-CONVENTION' and len(d.get('COLOUR-BASIS', '')) < 8:
        bad.append(('DC2', 'DECLARED-CONVENTION without a COLOUR-BASIS sentence'))

    if re.search(r'(?<![A-Za-z])L[123](?![0-9])', d['FIDELITY']):
        bad.append(('DC6', 'bare L in FIDELITY; use FL1-FL3'))

    enh = [e.strip() for e in d['ENHANCEMENT'].split(',') if e.strip()]
    for e in enh:
        if e not in ENHANCEMENTS:
            bad.append(('DC1', 'unregistered enhancement %r' % e))

    if d['FIDELITY'] == 'FL3' and d['ME5-COROLLARY'] != 'PRESENT':
        bad.append(('DC5', 'FL3 frame must carry ME5-COROLLARY: PRESENT'))

    t = d['TIME']
    m = re.search(r'ratio\s*=\s*([0-9.eE+-]+)', t)
    if not m:
        bad.append(('DC5', 'TIME lacks "ratio = ..." against t_rip'))
    elif float(m.group(1)) > 1.0 and d['ME5-COROLLARY'] != 'PRESENT':
        bad.append(('DC5', 'ratio > 1 (transient configuration) without ME5-COROLLARY: PRESENT'))

    if d['COLOUR'] == 'PHYSICAL' and d['BAND'] != 'NONE':
        bad.append(('DC2', 'PHYSICAL colour in a band requires a compliant sigma_s (G6); none exists'))

    return bad


def main():
    rows = []
    for dirpath, _dn, filenames in os.walk(RUNS):
        for fn in sorted(filenames):
            if fn.endswith('.display.txt'):
                p = os.path.join(dirpath, fn)
                rows.append((os.path.relpath(p, ROOT).replace('\\', '/'), check(p)))

    print("=" * 78)
    print("DISPLAY DECLARATION LINT  (rules DC1-DC8)")
    print("=" * 78)
    print("  scope: runs/**/*.display.txt   found: %d" % len(rows))
    print("  report only: no physics verdict, exit code always 0")
    print()

    nviol = 0
    for rel, bad in rows:
        if not bad:
            print("[OK]         %s" % rel)
        else:
            nviol += 1
            print("[VIOLATION]  %s" % rel)
            for rule, msg in bad:
                print("               %s  %s" % (rule, msg))

    print()
    print("  OK                 %d" % (len(rows) - nviol))
    print("  VIOLATION          %d" % nviol)
    print()
    if not rows:
        print("  No declaration exists yet -- there is no S0 frame to declare.")
        print("  This is the correct state before the first product, not a passing check:")
        print("  a validator that has never seen a block has certified nothing.")
    print()
    print("PROVENANCE: NEITHER  (convention enforcement report; establishes nothing)")
    print()
    print("Content generated by AI")


if __name__ == '__main__':
    main()
