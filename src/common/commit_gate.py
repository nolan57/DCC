"""
Commit instrument for the phased route (docs/decisions/phased_relaxation_route_v2.md §5).

G-64-01 (round 64) downgraded this from a GATE to an INSTRUMENT. It reads the three linters,
prints their counts, and ALWAYS returns 0. There is no "do not commit" verdict any more:
findings are facts recorded into the chain. The surviving hard constraint is scientific
honesty (a result-class label must not overstate what was proved), and it is enforced at
the product's registration, not here.

Invariant 3 is still *reported* per tool, because the two linters do not share a vocabulary:

    symbol_lint      MUST-FIX(A, C, D)   -- reported, never gates
    provenance_lint  flagged(VIOLATION + MISSING + INCOMPLETE) -- reported, never gates
    display_lint     VIOLATION           -- reported, never gates

Archived hits under runs/ are excluded from the symbol count by s9.1 (they cannot be edited).
"""
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
PY = sys.executable


def run(script):
    p = subprocess.run([PY, os.path.join(ROOT, 'src', 'common', script)],
                       capture_output=True, text=True, cwd=ROOT)
    return p.stdout


def main():
    sym = run('symbol_lint.py')
    prov = run('provenance_lint.py')
    disp = run('display_lint.py')

    m_sym = re.search(r'MUST-FIX total \(A, C, D\):\s*(\d+)', sym)
    # G-64-01: the label changed from "blocking" to "flagged"; accept either.
    m_prov = re.search(r'(?:flagged|blocking) \(VIOLATION \+ MISSING \+ INCOMPLETE\)\s*=\s*(\d+)', prov)
    m_disp = re.search(r'^\s+VIOLATION\s+(\d+)\s*$', disp, re.M)
    m_drift = re.search(r'drift observations \(DRIFT-OBSERVED\)\s*=\s*(\d+)', prov)

    sym_n = int(m_sym.group(1)) if m_sym else None
    prov_n = int(m_prov.group(1)) if m_prov else None
    disp_n = int(m_disp.group(1)) if m_disp else None
    drift_n = int(m_drift.group(1)) if m_drift else 0

    print("=" * 78)
    print("COMMIT INSTRUMENT  (report only since G-64-01; no veto, no 'do not commit')")
    print("=" * 78)
    print()
    print("  symbol_lint      MUST-FIX(A,C,D)                    = %s" % sym_n)
    print("  provenance_lint  flagged(VIOLATION+MISSING+INCOMP)  = %s" % prov_n)
    print("  provenance_lint  drift observations (DRIFT-OBS)    = %s" % drift_n)
    print("  display_lint     VIOLATION                          = %s" % disp_n)
    print()

    notes = []
    if sym_n is None or prov_n is None or disp_n is None:
        notes.append("a linter output could not be parsed")
    if sym_n:
        notes.append("%d symbol MUST-FIX" % sym_n)
    if prov_n:
        notes.append("%d provenance flags" % prov_n)
    if disp_n:
        notes.append("%d display violations" % disp_n)
    if drift_n:
        notes.append("%d registered drift observation(s)" % drift_n)

    print("  VERDICT: %s" % ("PASS-WITH-NOTES" if notes else "PASS-WITH-NOTES (clean)",))
    if notes:
        for n in notes:
            print("    NOTE: %s" % n)
    print()
    print("  Note: F is advisory. M1-M4 have five pre-existing legitimate owners;")
    print("  a report cannot retroactively invalidate archived labels (registry s2a).")
    print("  Nothing here blocks emission, registration or use of a product that passed its")
    print("  own CHECK/IDENT/NEGCTRL self-tests (G-64-01 rule 1: product is fact).")
    print()
    print("PROVENANCE: NEITHER  (instrument report for phased route v2 invariant 3)")
    print("Content generated by AI")
    # G-64-01: never a veto.
    return 0


if __name__ == '__main__':
    sys.exit(main())
